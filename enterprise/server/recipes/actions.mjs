// recipes.* as registry actions: each a Meteor method the app's Recipes tab calls, and (all but the
// permission and admin ones) an /api/v1 route, an exec call and an MCP tool, with the same checks
// (service.mjs). Scopes: recipes:read, recipes:write, recipes:run.
// Never a token's, a script's or MCP's: recipes.grant and recipes.revoke (a standing permission to
// change things outside Slatebox), recipes.decideWrite (approving one such change) and
// recipes.admin.* (the install switch): DDP only, people only, and NEVER_BOUND.
// Literal routes come before /recipes/{instanceId} (Express matches in order).
import { defineAction } from '/server/actions/registry.mjs'
import { cardIdInput, empty, grantIdInput, hookIdInput, hookOutput, instanceIdInput, obj, open, projectIdInput, recipeOutput, runIdInput, runOutput, shareIdInput, triggerInput } from './schemas.mjs'

const SERVICE = 'the recipes service records it (enterprise/server/recipes/service.mjs)'
const RUNS = 'each run is recorded by the runner as recipe.run, coalesced per recipe per hour'
const recipesBase = { toolset: 'recipes', principals: ['person', 'agent'] }
const write = { kind: 'write', idempotency: 'optional', changesNoSlate: true }
const people = { toolset: 'recipes', principals: ['person'], mounts: { ddp: true } }

/** The actions, over a getter for the running recipes service (set at server start). */
export function recipeActions(service) {
  const call = (fn) => async (principal, input) => ({ status: 200, body: await fn(service(), principal, input) })
  return [
    defineAction({
      ...recipesBase,
      id: 'recipes.catalog',
      title: 'Recipe catalog',
      description: 'The recipes this server offers: what each keeps up to date in a project (its slates and boards), when it runs, what it may propose to change outside Slatebox, the webhooks it sends, its cost class, and whether you have connected the integration it needs. on is false while recipes are turned off here.',
      kind: 'read',
      scope: 'recipes:read',
      mounts: { ddp: true, http: { method: 'GET', path: '/recipes/catalog', operationId: 'recipeCatalog' } },
      tool: { name: 'recipes_catalog', title: 'List recipes', description: 'List the recipes Slatebox can run in a project, with what each one makes.' },
      input: empty,
      output: open({ on: { type: 'boolean' }, recipes: { type: 'array', items: { type: 'object' } } }),
      handler: call((s, p) => s.catalog(p)),
    }),
    defineAction({
      ...recipesBase,
      id: 'recipes.hooks.list',
      title: 'Recipe webhooks',
      description: 'The webhooks on a recipe (instanceId) or on a whole project (projectId): outbound (where events go), inbound (a URL that runs the recipe with data) and intercepts (a service that steps into a run). Never a secret.',
      kind: 'read',
      scope: 'recipes:read',
      mounts: { ddp: true, http: { method: 'GET', path: '/recipes/hooks', operationId: 'listRecipeHooks' } },
      tool: { name: 'recipes_hooks_list', title: 'List recipe webhooks' },
      input: obj({ instanceId: instanceIdInput, projectId: projectIdInput }),
      output: open({ hooks: { type: 'array', items: hookOutput } }),
      handler: call((s, p, i) => s.hooksList(p, i)),
    }),
    defineAction({
      ...recipesBase,
      ...write,
      id: 'recipes.hooks.add',
      title: 'Add a recipe webhook',
      description: 'Add a webhook. outbound: Slatebox POSTs signed events (Slatebox-Signature: t=…,v1=HMAC-SHA256) to your https url; events lists which (all when empty). inbound: answers a URL that runs the recipe with the data you POST, signed the same way. intercept: your url is called during a run at point (graph.ready, output.ready, writeback.proposed) and may narrow what it does; failMode closed skips the run when your service does not answer. The secret is returned once.',
      scope: 'recipes:write',
      openWorld: true,
      mounts: { ddp: true, http: { method: 'POST', path: '/recipes/hooks', operationId: 'addRecipeHook' } },
      tool: { name: 'recipes_hooks_add', title: 'Add a recipe webhook' },
      input: obj({
        instanceId: instanceIdInput, projectId: projectIdInput,
        direction: { type: 'string', enum: ['outbound', 'inbound', 'intercept'] },
        url: { type: 'string', maxLength: 2000, description: 'outbound and intercept: a public https address.' },
        events: { type: 'array', maxItems: 40, items: { type: 'string', maxLength: 80 } },
        point: { type: 'string', enum: ['graph.ready', 'output.ready', 'writeback.proposed'] },
        failMode: { type: 'string', enum: ['open', 'closed'] },
      }, ['direction']),
      output: open({ hook: hookOutput, secret: { type: 'string', description: 'Shown once. Keep it where your receiver can read it.' }, url: { type: 'string' } }),
      audit: { inside: SERVICE },
      handler: call((s, p, i) => s.hooksAdd(p, i)),
    }),
    defineAction({
      ...recipesBase,
      id: 'recipes.deliveries',
      title: 'Webhook deliveries',
      description: 'The last deliveries of an outbound webhook (kept 14 days): event, attempt, state, the status your server answered and how long it took.',
      kind: 'read',
      scope: 'recipes:read',
      mounts: { ddp: true, http: { method: 'GET', path: '/recipes/hooks/{hookId}/deliveries', operationId: 'listRecipeDeliveries' } },
      tool: { name: 'recipes_deliveries', title: 'List webhook deliveries' },
      input: obj({ hookId: hookIdInput, limit: { type: 'integer', minimum: 1, maximum: 100 } }, ['hookId']),
      output: open({ deliveries: { type: 'array', items: { type: 'object' } } }),
      handler: call((s, p, i) => s.deliveriesOf(p, i.hookId, i)),
    }),
    defineAction({
      ...recipesBase,
      ...write,
      id: 'recipes.hooks.rotate',
      title: 'Rotate a webhook secret',
      description: 'A new secret for a webhook, returned once. The old one keeps signing beside it for 24 hours, so your receiver can switch. Turns a hook that was turned off after failures back on.',
      scope: 'recipes:write',
      mounts: { ddp: true, http: { method: 'POST', path: '/recipes/hooks/{hookId}/rotate', operationId: 'rotateRecipeHook' } },
      tool: { name: 'recipes_hooks_rotate', title: 'Rotate a webhook secret' },
      input: obj({ hookId: hookIdInput }, ['hookId']),
      output: open({ secret: { type: 'string' }, oldSecretRetiresAt: { type: 'string' } }),
      audit: { inside: SERVICE },
      handler: call((s, p, i) => s.hooksRotate(p, i.hookId)),
    }),
    defineAction({
      ...recipesBase,
      kind: 'write',
      idempotency: 'optional',
      readOnly: true,
      openWorld: true,
      id: 'recipes.hooks.test',
      title: 'Test a webhook',
      description: 'Send a signed ping to an outbound webhook now, and answer whether your server took it (a 2xx).',
      scope: 'recipes:write',
      mounts: { ddp: true, http: { method: 'POST', path: '/recipes/hooks/{hookId}/test', operationId: 'testRecipeHook' } },
      tool: { name: 'recipes_hooks_test', title: 'Test a webhook' },
      input: obj({ hookId: hookIdInput }, ['hookId']),
      output: open({ delivered: { type: 'boolean' }, status: { type: ['integer', 'null'] } }),
      handler: call((s, p, i) => s.hooksTest(p, i.hookId)),
    }),
    defineAction({
      ...recipesBase,
      ...write,
      id: 'recipes.hooks.remove',
      title: 'Remove a webhook',
      description: 'Remove a webhook; its waiting deliveries are dropped.',
      scope: 'recipes:write',
      destructive: true,
      changesNoSlate: undefined,
      mounts: { ddp: true, http: { method: 'DELETE', path: '/recipes/hooks/{hookId}', operationId: 'removeRecipeHook' } },
      tool: { name: 'recipes_hooks_remove', title: 'Remove a webhook' },
      input: obj({ hookId: hookIdInput }, ['hookId']),
      output: open({ removed: { type: 'boolean' } }),
      audit: { inside: SERVICE },
      handler: call((s, p, i) => s.hooksRemove(p, i.hookId)),
    }),
    defineAction({
      ...recipesBase,
      id: 'recipes.list',
      title: 'Recipes in a project',
      description: 'The recipes running in a project: who each runs for, whether it is on, its last and next run, and the slates it keeps.',
      kind: 'read',
      scope: 'recipes:read',
      mounts: { ddp: true, http: { method: 'GET', path: '/projects/{projectId}/recipes', operationId: 'listProjectRecipes' } },
      tool: { name: 'recipes_list', title: 'List recipes in a project' },
      input: obj({ projectId: projectIdInput }, ['projectId']),
      output: open({ recipes: { type: 'array', items: recipeOutput } }),
      handler: call((s, p, i) => s.list(p, i.projectId)),
    }),
    defineAction({
      ...recipesBase,
      ...write,
      id: 'recipes.create',
      title: 'Add a recipe to a project',
      description: 'Add a recipe to a project, to run for you: recipeId from recipes.catalog, its config (the recipe\'s configSchema) and optionally its triggers. It starts as a draft: preview it with recipes.preview, then turn it on with recipes.activate.',
      scope: 'recipes:write',
      mounts: { ddp: true, http: { method: 'POST', path: '/projects/{projectId}/recipes', operationId: 'createProjectRecipe' } },
      tool: { name: 'recipes_create', title: 'Add a recipe' },
      input: obj({ projectId: projectIdInput, recipeId: { type: 'string', pattern: '^[a-z][a-z0-9-]{2,40}$' }, config: { type: 'object' }, triggers: { type: 'array', maxItems: 8, items: triggerInput }, name: { type: 'string', maxLength: 120 } }, ['projectId', 'recipeId']),
      output: open({ recipe: recipeOutput }),
      audit: { inside: SERVICE },
      handler: call((s, p, i) => s.create(p, i.projectId, i)),
    }),
    defineAction({
      ...recipesBase,
      id: 'recipes.get',
      title: 'A recipe',
      description: 'One recipe: its settings, next run, the standing permissions it holds outside Slatebox, its webhooks, and changes outside Slatebox waiting for approval.',
      kind: 'read',
      scope: 'recipes:read',
      mounts: { ddp: true, http: { method: 'GET', path: '/recipes/{instanceId}', operationId: 'getRecipe' } },
      tool: { name: 'recipes_get', title: 'Read a recipe' },
      input: obj({ instanceId: instanceIdInput }, ['instanceId']),
      output: open({ recipe: recipeOutput, permissions: { type: 'array', items: { type: 'object' } }, hooks: { type: 'array', items: hookOutput }, waiting: { type: 'array', items: { type: 'object' } } }),
      handler: call((s, p, i) => s.get(p, i.instanceId)),
    }),
    defineAction({
      ...recipesBase,
      ...write,
      id: 'recipes.update',
      title: 'Change a recipe',
      description: 'Change a recipe that runs for you: its config, triggers, name, or applyMode (auto saves its updates directly on the slates it made, once you kept its first run\'s suggestions; suggest shows them for people to keep).',
      scope: 'recipes:write',
      mounts: { ddp: true, http: { method: 'PATCH', path: '/recipes/{instanceId}', operationId: 'updateRecipe' } },
      tool: { name: 'recipes_update', title: 'Change a recipe' },
      input: obj({ instanceId: instanceIdInput, config: { type: 'object' }, triggers: { type: 'array', maxItems: 8, items: triggerInput }, name: { type: 'string', maxLength: 120 }, applyMode: { type: 'string', enum: ['suggest', 'auto'] } }, ['instanceId']),
      output: open({ recipe: recipeOutput }),
      audit: { inside: SERVICE },
      handler: call((s, p, i) => s.update(p, i.instanceId, i)),
    }),
    defineAction({
      ...recipesBase,
      kind: 'write',
      idempotency: 'optional',
      readOnly: true,
      openWorld: true,
      id: 'recipes.preview',
      title: 'Preview a recipe',
      description: 'Run a recipe once without saving anything: each slate it would make or change (as slate JSON for a picture), the counts of notes added, changed and removed, and the tokens it used. Waits up to a minute.',
      scope: 'recipes:run',
      bodyLimit: '16kb',
      mounts: { ddp: true, http: { method: 'POST', path: '/recipes/{instanceId}/preview', operationId: 'previewRecipe' } },
      tool: { name: 'recipes_preview', title: 'Preview a recipe' },
      input: obj({ instanceId: instanceIdInput }, ['instanceId']),
      output: open({ runId: { type: 'string' }, state: { type: 'string' }, slates: { type: 'array', items: { type: 'object' } }, stats: { type: ['object', 'null'] }, log: { type: 'array', items: { type: 'object' } } }),
      handler: call((s, p, i) => s.preview(p, i.instanceId)),
    }),
    defineAction({
      ...recipesBase,
      ...write,
      id: 'recipes.activate',
      title: 'Turn a recipe on',
      description: 'Turn on a recipe that runs for you; its first run is queued at once. Its first run suggests (ghost notes people keep or discard); keep them to let later runs apply automatically.',
      scope: 'recipes:write',
      mounts: { ddp: true, http: { method: 'POST', path: '/recipes/{instanceId}/activate', operationId: 'activateRecipe' } },
      tool: { name: 'recipes_activate', title: 'Turn a recipe on' },
      input: obj({ instanceId: instanceIdInput }, ['instanceId']),
      output: open({ recipe: recipeOutput, runId: { type: 'string' } }),
      audit: { inside: SERVICE },
      handler: call((s, p, i) => s.activate(p, i.instanceId)),
    }),
    defineAction({
      ...recipesBase,
      ...write,
      id: 'recipes.run',
      title: 'Run a recipe now',
      description: 'Queue a run of a recipe that is on. data (the recipe\'s inputSchema) runs it with your data, as its inbound webhook would: a dependency graph from CI, a list from your own system. At most 30 an hour per recipe.',
      scope: 'recipes:run',
      bodyLimit: '256kb',
      mounts: { ddp: true, http: { method: 'POST', path: '/recipes/{instanceId}/run', operationId: 'runRecipe' } },
      tool: { name: 'recipes_run', title: 'Run a recipe now' },
      input: obj({ instanceId: instanceIdInput, reason: { type: 'string', maxLength: 200 }, data: { type: 'object' } }, ['instanceId']),
      output: open({ runId: { type: 'string' }, state: { type: 'string' } }),
      audit: { inside: RUNS },
      handler: call((s, p, i) => s.runNow(p, i.instanceId, i)),
    }),
    defineAction({
      ...recipesBase,
      ...write,
      id: 'recipes.pause',
      title: 'Pause a recipe',
      description: 'Pause a recipe: nothing runs until it is resumed, and its queued runs are cancelled. The person it runs for, or a manager of the project.',
      scope: 'recipes:write',
      mounts: { ddp: true, http: { method: 'POST', path: '/recipes/{instanceId}/pause', operationId: 'pauseRecipe' } },
      tool: { name: 'recipes_pause', title: 'Pause a recipe' },
      input: obj({ instanceId: instanceIdInput }, ['instanceId']),
      output: open({ recipe: recipeOutput }),
      audit: { inside: SERVICE },
      handler: call((s, p, i) => s.pause(p, i.instanceId)),
    }),
    defineAction({
      ...recipesBase,
      ...write,
      id: 'recipes.resume',
      title: 'Resume a recipe',
      description: 'Resume a paused recipe; its schedule picks up from now.',
      scope: 'recipes:write',
      mounts: { ddp: true, http: { method: 'POST', path: '/recipes/{instanceId}/resume', operationId: 'resumeRecipe' } },
      tool: { name: 'recipes_resume', title: 'Resume a recipe' },
      input: obj({ instanceId: instanceIdInput }, ['instanceId']),
      output: open({ recipe: recipeOutput }),
      audit: { inside: SERVICE },
      handler: call((s, p, i) => s.resume(p, i.instanceId)),
    }),
    defineAction({
      ...recipesBase,
      kind: 'write',
      idempotency: 'optional',
      destructive: true,
      id: 'recipes.delete',
      title: 'Delete a recipe',
      description: 'Delete a recipe from its project. The slates it made stay in the project (they become ordinary slates); its runs, webhooks and permissions go.',
      scope: 'recipes:write',
      mounts: { ddp: true, http: { method: 'DELETE', path: '/recipes/{instanceId}', operationId: 'deleteRecipe' } },
      tool: { name: 'recipes_delete', title: 'Delete a recipe' },
      input: obj({ instanceId: instanceIdInput }, ['instanceId']),
      output: open({ deleted: { type: 'boolean' } }),
      audit: { inside: SERVICE },
      handler: call((s, p, i) => s.remove(p, i.instanceId)),
    }),
    defineAction({
      ...recipesBase,
      id: 'recipes.runs',
      title: 'A recipe\'s runs',
      description: 'A recipe\'s runs, newest first: what started each, its state, how long it took, the tokens it used, what it changed (and whether that can be undone), what it did outside Slatebox, and its log. Pass next as before for older runs.',
      kind: 'read',
      scope: 'recipes:read',
      mounts: { ddp: true, http: { method: 'GET', path: '/recipes/{instanceId}/runs', operationId: 'listRecipeRuns' } },
      tool: { name: 'recipes_runs', title: 'List a recipe\'s runs' },
      input: obj({ instanceId: instanceIdInput, limit: { type: 'integer', minimum: 1, maximum: 50 }, before: { type: 'string', maxLength: 40 } }, ['instanceId']),
      output: open({ runs: { type: 'array', items: runOutput }, next: { type: ['string', 'null'] } }),
      handler: call((s, p, i) => s.runsOf(p, i.instanceId, i)),
    }),
    defineAction({
      ...recipesBase,
      kind: 'write',
      idempotency: 'optional',
      destructive: true,
      id: 'recipes.undoRun',
      title: 'Undo a recipe run',
      description: 'Take back what one run saved, slate by slate (slates.undo on each of its saves). What people changed since stays. Suggestions it left are kept or discarded on the slate instead.',
      scope: 'recipes:write',
      mounts: { ddp: true, http: { method: 'POST', path: '/recipe-runs/{runId}/undo', operationId: 'undoRecipeRun' } },
      tool: { name: 'recipes_undo_run', title: 'Undo a recipe run' },
      input: obj({ runId: runIdInput }, ['runId']),
      output: open({ undone: { type: 'integer' }, slates: { type: 'array', items: { type: 'string' } } }),
      audit: { inside: 'slates.undo records each slate it takes back (the save core)' },
      handler: call((s, p, i) => s.undoRun(p, i.runId)),
    }),
    defineAction({
      ...recipesBase,
      id: 'recipes.notesOn',
      title: 'Notes recipes keep on a slate',
      description: 'Which notes on a slate each recipe keeps up to date (note ids), with who it runs for. A note a person changed is theirs and is not listed.',
      kind: 'read',
      scope: 'recipes:read',
      mounts: { ddp: true, http: { method: 'GET', path: '/slates/{shareId}/recipe-notes', operationId: 'slateRecipeNotes' } },
      tool: { name: 'recipes_notes_on', title: 'Notes recipes keep on a slate' },
      input: obj({ shareId: shareIdInput }, ['shareId']),
      output: open({ recipes: { type: 'array', items: open({ instanceId: { type: 'string' }, name: { type: 'string' }, runsFor: { type: 'string' }, colorIndex: { type: 'integer' }, noteIds: { type: 'array', items: { type: 'string' } } }) } }),
      handler: call((s, p, i) => s.notesOn(p, i.shareId)),
    }),
    defineAction({
      ...recipesBase,
      ...write,
      id: 'recipes.makeMine',
      title: 'Make a note mine',
      description: 'Take over a note a recipe keeps: the recipe never changes or deletes it again. Anyone who can edit the slate.',
      scope: 'recipes:write',
      mounts: { ddp: true, http: { method: 'POST', path: '/slates/{shareId}/recipe-notes/{noteId}/mine', operationId: 'makeRecipeNoteMine' } },
      tool: { name: 'recipes_make_mine', title: 'Make a note mine' },
      input: obj({ shareId: shareIdInput, noteId: { type: 'string', minLength: 1, maxLength: 64, pattern: '^[A-Za-z0-9_-]+$' } }, ['shareId', 'noteId']),
      output: open({ noteId: { type: 'string' }, owner: { type: 'string' } }),
      audit: { off: 'which notes a recipe keeps; the slate itself does not change' },
      handler: call((s, p, i) => s.makeMine(p, i.shareId, i.noteId)),
    }),
    defineAction({
      ...recipesBase,
      ...write,
      id: 'recipes.transfer',
      title: 'Take a recipe over',
      description: 'A manager of the project takes a recipe over: it then runs for them, with their sign-ins. Its permissions outside Slatebox are cleared (grant them again); it waits paused until they resume it.',
      scope: 'recipes:write',
      mounts: { ddp: true, http: { method: 'POST', path: '/recipes/{instanceId}/transfer', operationId: 'transferRecipe' } },
      tool: { name: 'recipes_transfer', title: 'Take a recipe over' },
      input: obj({ instanceId: instanceIdInput }, ['instanceId']),
      output: open({ recipe: recipeOutput }),
      audit: { inside: SERVICE },
      handler: call((s, p, i) => s.transfer(p, i.instanceId)),
    }),
    // People only, in the app: never a token, a script or MCP (NEVER_BOUND).
    defineAction({
      ...people,
      ...write,
      id: 'recipes.grant',
      title: 'Let a recipe change something outside Slatebox',
      description: 'A standing permission: this recipe may make this kind of change, inside this scope, without asking each time (until expiresAt, when given). Signed-in people only.',
      scope: 'recipes:write',
      openWorld: true,
      input: obj({ instanceId: instanceIdInput, kind: { type: 'string', enum: ['github.check_run', 'github.pr_comment', 'github.pull_request', 'slack.post', 'google.write_sheet'] }, scope: { type: 'object' }, expiresAt: { type: 'string', maxLength: 40 } }, ['instanceId', 'kind', 'scope']),
      output: open({ grantId: { type: 'string' }, kind: { type: 'string' }, describe: { type: 'string' } }),
      audit: { inside: SERVICE },
      handler: call((s, p, i) => s.grant(p, i.instanceId, i)),
    }),
    defineAction({
      ...people,
      ...write,
      id: 'recipes.revoke',
      title: 'Take back a recipe\'s permission',
      description: 'Take back a standing permission. The recipe pauses until you resume it.',
      scope: 'recipes:write',
      input: obj({ grantId: grantIdInput }, ['grantId']),
      output: open({ revoked: { type: 'boolean' } }),
      audit: { inside: SERVICE },
      handler: call((s, p, i) => s.revoke(p, i.grantId)),
    }),
    defineAction({
      ...people,
      ...write,
      id: 'recipes.decideWrite',
      title: 'Approve or decline a change outside Slatebox',
      description: 'Answer a change a recipe proposed outside Slatebox: approve makes it once, now (checked again against its limits); decline closes it. The person the recipe runs for, signed in.',
      scope: 'recipes:write',
      openWorld: true,
      input: obj({ cardId: cardIdInput, decision: { type: 'string', enum: ['approve', 'decline'] } }, ['cardId', 'decision']),
      output: open({ state: { type: 'string' }, ref: { type: ['string', 'null'] } }),
      audit: { inside: 'the permissions record recipe.outside_write for a change made (enterprise/server/recipes/permissions.mjs)' },
      handler: call((s, p, i) => s.decideWrite(p, i.cardId, i.decision)),
    }),
    defineAction({
      ...people,
      id: 'recipes.admin.status',
      title: 'Recipes on this server',
      description: 'Whether recipes are on here, how many run, and the limits. Server administrators only.',
      kind: 'read',
      scope: 'recipes:read',
      input: empty,
      output: open({ enabled: { type: 'boolean' }, serverOff: { type: 'boolean' }, counts: { type: 'object' }, limits: { type: 'object' } }),
      handler: call((s, p) => s.adminStatus(p)),
    }),
    defineAction({
      ...people,
      ...write,
      id: 'recipes.admin.setEnabled',
      title: 'Turn recipes on or off on this server',
      description: 'The install switch (Admin › Recipes): on, people may add and run recipes; off, none run and none can be added. Server administrators only.',
      scope: 'recipes:write',
      input: obj({ enabled: { type: 'boolean' } }, ['enabled']),
      output: open({ enabled: { type: 'boolean' }, counts: { type: 'object' } }),
      audit: { inside: SERVICE },
      handler: call((s, p, i) => s.setInstallEnabled(p, i.enabled)),
    }),
  ]
}
